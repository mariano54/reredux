#!/usr/bin/env python3
"""Export all message banks of both ROMs as editable text and summarize Redux's text changes.

  build/src/{redux,vanilla}/text/{system,story}/NNNN.txt   (lossless, see gen5text.py)
  notes/text-changes.md                                     changed banks + sample lines
"""
import difflib, os, struct
import ndsfs, gen5text as G
import redux_rom as R

BANKS = {'system': 'a/0/0/2', 'story': 'a/0/0/3'}


def export(rom_path, label):
    rom = ndsfs.Rom(rom_path)
    ids = {p: i for i, p in rom.paths.items()}
    out = {}
    for kind, path in BANKS.items():
        d = os.path.join(R.BUILD, 'src', label, 'text', kind)
        os.makedirs(d, exist_ok=True)
        banks = ndsfs.narc(rom.file(ids[path]))
        out[kind] = []
        for i, b in enumerate(banks):
            txt = G.to_file(G.decode(b), G.padding(b))
            unk = struct.unpack('<I', b[8:12])[0]
            assert G.encode(*G.from_file(txt)[:1], unk, G.from_file(txt)[1]) == b, (label, kind, i)
            with open(os.path.join(d, f'{i:04d}.txt'), 'w', encoding='utf-8') as f:
                f.write(txt)
            out[kind].append(txt)
    return out


def main():
    van = export(os.path.join(R.BUILD, 'vanilla_rom', 'black2.nds'), 'vanilla')
    red = export(os.path.join(R.BUILD, 'vanilla_rom', 'redux.nds'), 'redux')
    lines = ['# Redux text changes (generated by tools/export_text.py)\n',
             'Banks exported losslessly to build/src/{redux,vanilla}/text/; all banks re-encode byte-exact.\n']
    for kind in BANKS:
        changed = [i for i, (a, b) in enumerate(zip(van[kind], red[kind])) if a != b]
        tot = sum(sum(1 for l in difflib.ndiff(van[kind][i].split("\n"), red[kind][i].split("\n"))
                      if l.startswith('+ ')) for i in changed)
        lines.append(f'\n## {kind} ({BANKS[kind]}): {len(changed)} of {len(red[kind])} banks changed, ~{tot} lines added/rewritten\n')
        lines.append('| bank | vanilla lines | redux lines | sample new line |\n|---|---|---|---|\n')
        for i in changed:
            a, b = van[kind][i].split("\n"), red[kind][i].split("\n")
            new = [l for l in b if l not in set(a)]
            sample = (new[0] if new else '').replace('|', '\\|')[:90]
            lines.append(f'| {i:04d} | {len(a)} | {len(b)} | {sample} |\n')
    with open(os.path.join(R.ROOT, 'notes', 'text-changes.md'), 'w', encoding='utf-8') as f:
        f.writelines(lines)
    print(''.join(lines[:3]))


if __name__ == '__main__':
    main()
