#!/usr/bin/env python3
"""Export B2W2 data tables of both ROMs to JSON and summarize Redux's data changes.

  build/src/{redux,vanilla}/data/{trainers,encounters,personal,learnsets,evolutions,moves,items}.json
  notes/data-changes.md
Every table is checked to re-encode byte-exact before it is written.
"""
import json, os
import ndsfs, gen5data as D
import redux_rom as R

TABLES = {  # name: (narc, decode(raw, names, types), encode(entries, names, types))
    'trainers': (('a/0/9/1', 'a/0/9/2'), None, None),
    'encounters': ('a/1/2/7', lambda r, n, t: D.decode_encounters(r, n), lambda e, n, t: D.encode_encounters(e, n)),
    'personal': ('a/0/1/6', D.decode_personal, D.encode_personal),
    'learnsets': ('a/0/1/8', lambda r, n, t: D.decode_learnsets(r, n), lambda e, n, t: D.encode_learnsets(e, n)),
    'evolutions': ('a/0/1/9', lambda r, n, t: D.decode_evolutions(r, n), lambda e, n, t: D.encode_evolutions(e, n)),
    'moves': ('a/0/2/1', D.decode_moves, D.encode_moves),
    'items': ('a/0/2/4', lambda r, n, t: D.decode_items(r, n), lambda e, n, t: D.encode_items(e, n)),
}


def export(rom_path, label):
    rom = ndsfs.Rom(rom_path)
    ids = {p: i for i, p in rom.paths.items()}
    get = lambda p: ndsfs.narc(rom.file(ids[p]))
    sysb = get('a/0/0/2')
    names = D.Names(sysb)
    types = D.name_list(sysb[398]) + ['Fairy']     # Redux adds type 17; vanilla never uses it
    out_dir = os.path.join(R.BUILD, 'src', label, 'data')
    os.makedirs(out_dir, exist_ok=True)
    res = {}
    for name, (narc, dec, enc) in TABLES.items():
        if name == 'trainers':
            td, tp = get(narc[0]), get(narc[1])
            ents = D.decode_trainers(td, tp, names)
            a, b = D.encode_trainers(json.loads(json.dumps(ents)), names)
            assert a == td and b == tp, (label, name)
        else:
            raw = get(narc)
            ents = dec(raw, names, types)
            assert enc(json.loads(json.dumps(ents)), names, types) == raw, (label, name)
        with open(os.path.join(out_dir, f'{name}.json'), 'w', encoding='utf-8') as f:
            json.dump(ents, f, ensure_ascii=False, indent=1)
        res[name] = ents
    return res, names


def strip(e):
    return {k: v for k, v in e.items() if k != 'id'}


def main():
    van, _ = export(os.path.join(R.BUILD, 'vanilla_rom', 'black2.nds'), 'vanilla')
    red, names = export(os.path.join(R.BUILD, 'vanilla_rom', 'redux.nds'), 'redux')
    L = ['# Redux data changes (generated by tools/export_data.py)\n\n',
         'All tables exported to build/src/{redux,vanilla}/data/*.json and re-encode byte-exact.\n\n']
    for name in TABLES:
        v, r = van[name], red[name]
        changed = [i for i in range(len(r)) if i >= len(v) or strip(v[i]) != strip(r[i])]
        L.append(f'- **{name}**: {len(changed)} of {len(r)} entries changed or added (vanilla {len(v)})\n')
    # new trainers
    vt, rt = van['trainers'], red['trainers']
    L.append(f'\n## New trainers ({len(rt) - len(vt)})\n\n| id | class | name | battle | party |\n|---|---|---|---|---|\n')
    for t in rt[len(vt):]:
        party = ', '.join(f"{m['species']} {m['level']}" for m in t.get('party', []))
        L.append(f"| {t['id']} | {t.get('trainer_class', '')} | {t.get('name', '')} | {t.get('battle_type', '')} | {party} |\n")
    # moves
    L.append('\n## Move changes\n\n| move | type | category | power | accuracy | pp | priority |\n|---|---|---|---|---|---|---|\n')
    for a, b in zip(van['moves'], red['moves']):
        if strip(a) != strip(b):
            cell = lambda k: f'{a[k]} → {b[k]}' if a[k] != b[k] else f'{b[k]}'
            nm = a['name'] if a['name'] == b['name'] else f"{a['name']} → {b['name']}"
            L.append(f"| {nm} | {cell('type')} | {cell('category')} | {cell('power')} | {cell('accuracy')} | "
                     f"{cell('pp')} | {cell('priority')} |\n")
    # personal: types / stats / abilities
    L.append('\n## Pokémon type, stat and ability changes\n\n| Pokémon | types | stats (HP/Atk/Def/Spe/SpA/SpD) | abilities |\n|---|---|---|---|\n')
    st = ['hp', 'atk', 'def', 'spe', 'spa', 'spd']
    for a, b in zip(van['personal'], red['personal']):
        if '_raw' in a or '_raw' in b or a['id'] == 0:
            continue
        ty = lambda e: f"{e['type1']}/{e['type2']}" if e['type1'] != e['type2'] else e['type1']
        sa, sb = '/'.join(str(a[k]) for k in st), '/'.join(str(b[k]) for k in st)
        ab = lambda e: f"{e['ability1']},{e['ability2']},{e['ability_hidden']}"
        if ty(a) != ty(b) or sa != sb or ab(a) != ab(b):
            L.append(f"| {b['name']} | {ty(a) + ' → ' + ty(b) if ty(a) != ty(b) else ty(b)} | "
                     f"{sa + ' → ' + sb if sa != sb else ''} | {ab(a) + ' → ' + ab(b) if ab(a) != ab(b) else ''} |\n")
    # evolutions
    L.append('\n## Evolution changes (method, parameter, target)\n\n| Pokémon | vanilla | Redux |\n|---|---|---|\n')
    for a, b in zip(van['evolutions'], red['evolutions']):
        if a['evolutions'] != b['evolutions']:
            f = lambda e: '; '.join(f'{m},{p},{t}' for m, p, t, _ in e['evolutions'])
            L.append(f"| {b['name']} | {f(a)} | {f(b)} |\n")
    with open(os.path.join(R.ROOT, 'notes', 'data-changes.md'), 'w', encoding='utf-8') as fh:
        fh.writelines(L)
    print(''.join(L[2:2 + len(TABLES)]))


if __name__ == '__main__':
    main()
