#!/usr/bin/env python3
"""Diff Redux's arm9 (static main + ITCM) against vanilla and write notes/arm9-changes.{md,json}.

Redux bytes come from the decoded patch. Unknown bytes (copied from vanilla) are filled from the
GAS-built vanilla image when the copy provably came from the same address (uncompressed arm9
head); other unknown bytes are assumed unchanged and counted as `unverified` per function.
"""
import bisect, json, os, re, sys
import redux_rom as R
import diffutil as D

ITCM_RAM = 0x01FF8000
ITCM_IN_ARM9 = 0x0209D740   # ITCM autoload block (RAM 0x01FF8000) sits right after the static image
ARM9_HEAD_END = 0x02008000  # vanilla arm9 is BLZ-compressed except its first 16 KiB


def redux_view(rom, van, rom_off_of):
    n = len(van.data)
    red = bytearray(n)
    known = bytearray(n)
    unverified = bytearray(n)
    for i in range(n):
        o = rom_off_of(van.base + i)
        if rom.known(o):
            red[i] = rom.k0[o]
            known[i] = 1
            continue
        red[i] = van.data[i]
        s = rom.source_offset(o)
        if s == o and van.base + i < ARM9_HEAD_END:
            known[i] = 1
        elif s is not None and 0x4000 <= s < 0x4000 + (ARM9_HEAD_END - R.ARM9_RAM):
            v = van.at(s - 0x4000 + R.ARM9_RAM)
            if v is not None:
                red[i] = v[0]
                known[i] = 1
                continue
            unverified[i] = 1
        else:
            unverified[i] = 1
    return bytes(red), bytes(known), bytes(unverified)


def section_of(meta, addr):
    for s in meta['sections']:
        if s['base'] <= addr < s['base'] + s['size']:
            return s['name']
    return '?'


def analyse(module, rom, rom_off_of, names, seg):
    van = R.Vanilla(module)
    red, known, unv = redux_view(rom, van, rom_off_of)
    diffs = D.real_diffs(van.data, red, known, van.base)
    funcs = R.functions(module)
    starts = [f[0] for f in funcs]
    groups = {}
    for a, b in D.runs(diffs):
        sec = section_of(van.meta, a)
        if sec in ('.text', '.itcm'):
            k = bisect.bisect_right(starts, a) - 1
            key = funcs[k] if k >= 0 else (a, f'_{a:08X}', 'thumb')
        else:
            key = (None, sec, None)
        groups.setdefault(key, []).append((a, b))
    out = []
    for (fa, fname, mode), rs in sorted(groups.items(), key=lambda kv: kv[1][0][0]):
        entry = {'module': module, 'kind': 'function' if fa else 'data', 'runs': [[f'{a:08X}', b - a + 1] for a, b in rs],
                 'bytes': sum(b - a + 1 for a, b in rs)}
        if fa:
            k = starts.index(fa)
            end = starts[k + 1] if k + 1 < len(starts) else van.base + len(van.data)
            entry.update(addr=f'{fa:08X}', placeholder=fname, name=names.get((seg, fa)), mode=mode, size=end - fa,
                         unverified=sum(unv[fa - van.base:end - van.base]))
            v_lines = D.disasm(van.data[fa - van.base:end - van.base], fa, mode)
            r_lines = D.disasm(red[fa - van.base:end - van.base], fa, mode)
            changed = []
            rmap = {l[0]: l for l in r_lines}
            for addr, hx, ins in v_lines:
                r = rmap.get(addr)
                if r and r[1] != hx and any(a <= addr + 3 and addr <= b for a, b in rs):
                    if re.match(r'blx? 0x2004000$', ins):
                        continue   # call to an unresolved extern (DSProt): can't compare
                    changed.append({'addr': f'{addr:08X}', 'vanilla': ins, 'redux': r[2]})
            entry['changes'] = changed
            if not changed:
                continue
        else:
            entry['hex'] = [{'addr': f'{a:08X}', 'vanilla': van.data[a - van.base:b - van.base + 1].hex(),
                             'redux': red[a - van.base:b - van.base + 1].hex()} for a, b in rs]
        out.append(entry)
    stats = dict(module=module, size=len(van.data), known=sum(known), unverified=sum(unv), diff_bytes=len(diffs),
                 functions_changed=sum(1 for e in out if e['kind'] == 'function'))
    return stats, out


def write_md(path, stats, entries):
    with open(path, 'w') as f:
        f.write('# Redux arm9 changes (generated by tools/arm9_changes.py)\n\n')
        f.write('Vanilla = pokeblack2 assembled with GNU as; Redux = Blaze Black 2 Redux v1.4.1 Complete.\n')
        f.write('GAS encoding artifacts are filtered. `unverified` = bytes copied from vanilla that we could not\n'
                'reconstruct without a ROM (assumed unchanged).\n\n')
        f.write('| module | size | known | unverified | changed bytes | functions changed |\n|---|---|---|---|---|---|\n')
        for s in stats:
            f.write(f"| {s['module']} | {s['size']} | {s['known']} | {s['unverified']} | {s['diff_bytes']} | {s['functions_changed']} |\n")
        for e in entries:
            if e['kind'] == 'function':
                title = f"{e['addr']} {e['name'] or e['placeholder']}" + (f" ({e['placeholder']})" if e['name'] else '')
                f.write(f"\n## {title}\n\n{e['module']}, {e['mode']}, {e['size']} bytes, {e['bytes']} changed, {e['unverified']} unverified\n\n")
                if e['changes']:
                    f.write('```\n')
                    for c in e['changes']:
                        f.write(f"{c['addr']}  {c['vanilla']:<36} -> {c['redux']}\n")
                    f.write('```\n')
            else:
                f.write(f"\n## data {e['module']} {e['runs'][0][0]} ({e['bytes']} bytes in {len(e['runs'])} runs)\n\n```\n")
                for h in e['hex'][:40]:
                    f.write(f"{h['addr']}  {h['vanilla'][:64]}\n          {h['redux'][:64]}\n")
                f.write('```\n')


def main():
    rom = R.ReduxRom()
    names = R.names()
    arm9 = lambda a: R.ARM9_ROM + a - R.ARM9_RAM
    itcm = lambda a: R.ARM9_ROM + (ITCM_IN_ARM9 - R.ARM9_RAM) + (a - ITCM_RAM)
    s1, e1 = analyse('main', rom, arm9, names, 'ARM9')
    s2, e2 = analyse('itcm', rom, itcm, names, 'ITCM')
    notes = os.path.join(R.ROOT, 'notes')
    os.makedirs(notes, exist_ok=True)
    json.dump({'stats': [s1, s2], 'changes': e1 + e2}, open(os.path.join(notes, 'arm9-changes.json'), 'w'), indent=1)
    write_md(os.path.join(notes, 'arm9-changes.md'), [s1, s2], e1 + e2)
    for s in (s1, s2):
        print(s)


if __name__ == '__main__':
    sys.exit(main())
