#!/usr/bin/env python3
"""Exact vanilla-vs-Redux diff using a real Black 2 ROM (build/vanilla_rom/black2.nds, SHA-1
e51e6dfb...) and the patched ROM (build/vanilla_rom/redux.nds).

Writes notes/rom-diff.md + notes/rom-diff.json, and extracts both versions of every changed
file to build/files/{vanilla,redux}/ (overlays and arm9 decompressed, NARCs split into subfiles).
"""
import json, os, subprocess, sys, tempfile
import ndsfs
import redux_rom as R

V = os.path.join(R.BUILD, 'vanilla_rom', 'black2.nds')
X = os.path.join(R.BUILD, 'vanilla_rom', 'redux.nds')
OUT = os.path.join(R.BUILD, 'files')
BLZ = os.path.join(R.BUILD, 'bin', 'blz')


def unblz(data):
    if len(data) < 8 or data[-8:] == bytes(8):
        return bytes(data)
    with tempfile.TemporaryDirectory() as t:
        i, o = os.path.join(t, 'i'), os.path.join(t, 'o')
        open(i, 'wb').write(data)
        r = subprocess.run([BLZ, '-d', i, o], capture_output=True)
        return open(o, 'rb').read() if r.returncode == 0 else bytes(data)


def nbytes_diff(a, b):
    return sum(1 for x, y in zip(a, b) if x != y) + abs(len(a) - len(b))


def save(kind, rel, data):
    p = os.path.join(OUT, kind, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, 'wb').write(data)


def main():
    v, x = ndsfs.Rom(V), ndsfs.Rom(X)
    rows = []
    # arm9: vanilla stored BLZ-compressed, Redux stored decompressed
    va = unblz(v.m[v.arm9[0]:v.arm9[0] + v.arm9[1]])
    xa = bytes(x.m[x.arm9[0]:x.arm9[0] + x.arm9[1]])
    xa = unblz(xa) if xa[-8:] != bytes(8) and len(xa) < len(va) else xa
    rows.append(dict(path='arm9', vanilla=len(va), redux=len(xa), diff=nbytes_diff(va, xa)))
    save('vanilla', 'arm9.bin', va); save('redux', 'arm9.bin', xa)
    # overlays
    vo, xo = v.overlays(), x.overlays()
    for a, b in zip(vo, xo):
        vf, xf = v.file(a['file_id']), x.file(b['file_id'])
        if vf == xf and a == b:
            continue
        vd = unblz(vf) if a['compressed'] else bytes(vf)
        xd = unblz(xf) if b['compressed'] else bytes(xf)
        shift = a['ram'] - b['ram']
        d = nbytes_diff(vd, xd[shift:]) if shift >= 0 else nbytes_diff(vd, xd)
        rows.append(dict(path=f"overlay_{a['id']}", vanilla=len(vd), redux=len(xd), diff=d,
                         ram=f"{a['ram']:08X}->{b['ram']:08X}" if shift else f"{a['ram']:08X}",
                         recompressed=vf != xf))
        save('vanilla', f"overlay_{a['id']}.bin", vd); save('redux', f"overlay_{a['id']}.bin", xd)
    # data files
    for fid, path in sorted(v.paths.items()):
        vf, xf = v.file(fid), x.file(fid)
        if vf == xf:
            continue
        row = dict(path=path, vanilla=len(vf), redux=len(xf), diff=nbytes_diff(vf, xf))
        vn, xn = ndsfs.narc(vf), ndsfs.narc(xf)
        if vn is not None and xn is not None:
            changed = [i for i in range(max(len(vn), len(xn)))
                       if i >= len(vn) or i >= len(xn) or vn[i] != xn[i]]
            row.update(subfiles=f'{len(vn)}->{len(xn)}', changed_subfiles=len(changed),
                       added=max(0, len(xn) - len(vn)))
            for i in changed:
                if i < len(vn):
                    save('vanilla', f'{path}/{i:04d}.bin', vn[i])
                if i < len(xn):
                    save('redux', f'{path}/{i:04d}.bin', xn[i])
        else:
            save('vanilla', path, bytes(vf)); save('redux', path, bytes(xf))
        rows.append(row)
    notes = os.path.join(R.ROOT, 'notes')
    json.dump(rows, open(os.path.join(notes, 'rom-diff.json'), 'w'), indent=1)
    with open(os.path.join(notes, 'rom-diff.md'), 'w') as f:
        f.write('# Exact Redux vs vanilla diff (generated by tools/rom_diff.py)\n\n'
                'Vanilla = Black 2 USA/EU (SHA-1 e51e6dfb8678a3d19dcd2a10691b96a569ca0abb); Redux = '
                'v1.4.1 Complete applied with xdelta3 (checksums verified). Overlays/arm9 compared '
                'decompressed; NARCs per subfile.\n\n')
        f.write('| file | vanilla B | redux B | bytes differing | subfiles | changed subfiles | notes |\n|---|---|---|---|---|---|---|\n')
        for r in rows:
            note = ' '.join(f'{k}={r[k]}' for k in ('ram', 'added') if r.get(k))
            f.write(f"| {r['path']} | {r['vanilla']} | {r['redux']} | {r['diff']} | {r.get('subfiles', '')} | "
                    f"{r.get('changed_subfiles', '')} | {note} |\n")
    for r in rows:
        print(json.dumps(r))


if __name__ == '__main__':
    sys.exit(main())
