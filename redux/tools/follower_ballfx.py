#!/usr/bin/env python3
"""HGSS follower Poké Ball effect models -> Black 2's field-effect archive a/0/7/4 (followers/ballfx.c).

The three files come from the HGSS decomp tree at build time (nothing from HGSS is committed):
files/a/1/0/3 members 0x81 (monsterball BMD0), 0x68 (mb_out BMD0) and 0xA4 (mb_out BTA0). They are
appended to a/0/7/4 (vanilla / Redux: 159 members -> new ids 159, 160, 161); ballfx_ids.h gives
ballfx.c the ids. Rebuilding from a ROM that already has them reuses their ids.

  follower_ballfx.py ROM HGSS_ROOT      print the member ids the ROM would get
"""
import os, struct, sys
import ndsfs

ARC = 'a/0/7/4'                 # ARCID 0x4A, FieldEffects' ArcTool
HGSS_ARC = os.path.join('a', '1', '0', '3')
MEMBERS = (('BALL', 0x81, b'BMD0'), ('BURST', 0x68, b'BMD0'), ('BURST_ANM', 0xA4, b'BTA0'))


def hgss_root_of(path):
    """HGSS 'files' directory from the decomp root, its files/ dir, or any path inside it (such as
    build_followers.py's --hgss .../files/data/mmodel/mmodel)."""
    p = os.path.abspath(path)
    while True:
        for cand in (p, os.path.join(p, 'files')):
            if os.path.isfile(os.path.join(cand, HGSS_ARC)):
                return cand
        if os.path.dirname(p) == p:
            raise FileNotFoundError(f'no {HGSS_ARC} above {path}')
        p = os.path.dirname(p)


def _dict(d, at):
    """NNS G3D resource dictionary at `at` -> [(name, entry bytes)]"""
    n = d[at + 1]
    ofs = at + struct.unpack_from('<H', d, at + 6)[0]
    unit, names = struct.unpack_from('<HH', d, ofs)
    return [(d[ofs + names + 16 * i:ofs + names + 16 * (i + 1)].rstrip(b'\0'),
             d[ofs + 4 + unit * i:ofs + 4 + unit * (i + 1)]) for i in range(n)]


def full_bright(bmd):
    """Give lit materials a white emission. monsterball is lit by light 0 with material ambient
    white, which under HGSS's white field light is the plain texture; B2's field lights are dimmer
    and draw the ball dark. Emission (added before the clamp) gives HGSS's colours under any light.
    (Turning lighting off instead draws it black: its display list sets the colour via normals.)"""
    d = bytearray(bmd)
    mdl0 = struct.unpack_from('<I', d, 0x10)[0]
    assert d[mdl0:mdl0 + 4] == b'MDL0'
    for _, ent in _dict(d, mdl0 + 8):
        m = mdl0 + struct.unpack_from('<I', ent, 0)[0]
        mat = m + struct.unpack_from('<I', d, m + 8)[0]
        for _, ment in _dict(d, mat + 4):
            o = mat + struct.unpack_from('<I', ment, 0)[0]
            spec_emi, poly = struct.unpack_from('<II', d, o + 8)
            if poly & 0xF:
                struct.pack_into('<I', d, o + 8, spec_emi & 0xFFFF | 0x7FFF << 16)
    return bytes(d)


def hgss_files(hgss_root):
    members = ndsfs.narc(open(os.path.join(hgss_root_of(hgss_root), HGSS_ARC), 'rb').read())
    out = []
    for name, idx, magic in MEMBERS:
        data = members[idx]
        assert data[:4] == magic, f'HGSS a/1/0/3 member {idx:#x} is not {magic}'
        out.append((name, full_bright(data) if magic == b'BMD0' else data))
    return out


def ids_header(ids):
    body = ''.join(f'#define BALLFX_DAT_{name} {i}\n' for name, i in ids.items())
    return ('/* generated by tools/follower_ballfx.py: a/0/7/4 members holding the HGSS ball models */\n'
            '#ifndef BALLFX_IDS_H\n#define BALLFX_IDS_H\n' + body + '#endif\n')


def ball_assets(rom, hgss_root, header_dir=None):
    """-> {file id: new a/0/7/4 NARC}; empty if the ROM already has the models. Writes
    header_dir/ballfx_ids.h when given. The ids are also in the module global LAST_IDS."""
    global LAST_IDS
    fid = next(f for f, p in rom.paths.items() if p == ARC)
    raw = rom.file(fid)
    members = ndsfs.narc(raw)
    ids, out = {}, {}
    for name, data in hgss_files(hgss_root):
        if data in members:
            ids[name] = members.index(data)
        else:
            ids[name] = len(members)
            members.append(data)
    if len(members) != len(ndsfs.narc(raw)):
        out[fid] = ndsfs.pack_narc(members, ndsfs.narc_layout(raw))
        assert ndsfs.narc(out[fid]) == members
    LAST_IDS = ids
    if header_dir:
        os.makedirs(header_dir, exist_ok=True)
        open(os.path.join(header_dir, 'ballfx_ids.h'), 'w').write(ids_header(ids))
    return out


LAST_IDS = None

if __name__ == '__main__':
    r = ndsfs.Rom(sys.argv[1])
    files = ball_assets(r, sys.argv[2])
    print(f'{ARC}: {len(ndsfs.narc(r.file(next(f for f, p in r.paths.items() if p == ARC))))} members;',
          ', '.join(f'{k} = {v}' for k, v in LAST_IDS.items()), '(appended)' if files else '(already present)')
