#!/usr/bin/env python3
"""Diff recovered Redux overlays (build/overlays/redux_overlay_N.bin, from recover_overlays.py)
against vanilla and write notes/overlay-changes.{md,json}.

usage: overlay_changes.py N...
"""
import bisect, json, os, re, sys
import redux_rom as R, diffutil as D


def analyse(n, rom, names):
    van = R.Vanilla(f'overlay_{n}')
    red = open(os.path.join(R.BUILD, 'overlays', f'redux_overlay_{n}.bin'), 'rb').read()
    ent = rom.overlay_entry(n)
    ram = ent['ram'] if all(ent['known'][4:8]) else van.base
    shift = van.base - ram
    aligned = red[shift:shift + len(van.data)]
    tpath = os.path.join(R.BUILD, 'overlays', f'redux_overlay_{n}.taint')
    taint = open(tpath, 'rb').read()[shift:shift + len(van.data)] if os.path.exists(tpath) else bytes(len(aligned))
    known = bytes(1 - t for t in taint)   # bytes that depend on unrecoverable stream bytes are skipped
    diffs = D.real_diffs(van.data, aligned, known, van.base)
    funcs = R.functions(f'overlay_{n}')
    starts = [f[0] for f in funcs]
    groups = {}
    for a, b in D.runs(diffs):
        sec = next((s['name'] for s in van.meta['sections'] if s['base'] <= a < s['base'] + s['size']), '?')
        if sec == '.text' and starts:
            k = max(0, bisect.bisect_right(starts, a) - 1)
            key = funcs[k]
        else:
            key = (None, sec, None)
        groups.setdefault(key, []).append((a, b))
    out = []
    for (fa, fname, mode), rs in sorted(groups.items(), key=lambda kv: kv[1][0][0]):
        e = {'overlay': n, 'kind': 'function' if fa else 'data', 'bytes': sum(b - a + 1 for a, b in rs),
             'runs': [[f'{a:08X}', b - a + 1] for a, b in rs]}
        if fa:
            k = starts.index(fa)
            end = starts[k + 1] if k + 1 < len(starts) else van.base + len(van.data)
            e.update(addr=f'{fa:08X}', placeholder=fname, name=names.get((f'OVL_{n}', fa)), mode=mode, size=end - fa)
            v = D.disasm(van.data[fa - van.base:end - van.base], fa, mode)
            r = {l[0]: l for l in D.disasm(aligned[fa - van.base:end - van.base], fa, mode)}
            e['changes'] = [{'addr': f'{a:08X}', 'vanilla': ins, 'redux': r[a][2]}
                            for a, hx, ins in v if a in r and r[a][1] != hx and any(x <= a + 3 and a <= y for x, y in rs)]
        else:
            e['hex'] = [{'addr': f'{a:08X}', 'vanilla': van.data[a - van.base:b - van.base + 1].hex(),
                         'redux': aligned[a - van.base:b - van.base + 1].hex()} for a, b in rs]
        out.append(e)
    front = None
    if shift > 0:
        front = {'ram': f'{ram:08X}', 'size': shift, 'thumb': D.disasm(red[:shift], ram, 'thumb'),
                 'hex': red[:shift].hex()}
    stats = dict(overlay=n, ram=f'{ram:08X}', vanilla_ram=f'{van.base:08X}', size=len(red),
                 vanilla_size=len(van.data), front=shift, diff_bytes=len(diffs), unverifiable=sum(taint),
                 functions_changed=sum(1 for e in out if e['kind'] == 'function'))
    return stats, out, front


def write_md(path, results):
    with open(path, 'w') as f:
        f.write('# Redux overlay changes (generated by tools/overlay_changes.py)\n\n')
        f.write('Recovered from the Redux patch without a ROM (recover_overlays.py): literal bytes + copies\n'
                'filled from a byte-exact vanilla model. GAS encoding artifacts filtered.\n\n')
        f.write('`unverifiable` = output bytes that depend on stream bytes copied from vanilla regions we\n'
                'cannot rebuild (excluded from the diff). ov36 had its 49 such holes inferred by\n'
                'blzsolve.py (biased toward vanilla), so its list may miss changes near those holes.\n\n')
        f.write('| overlay | Redux RAM | vanilla RAM | new front bytes | changed bytes | unverifiable | functions changed |\n|---|---|---|---|---|---|---|\n')
        for s, _, _ in results:
            f.write(f"| {s['overlay']} | {s['ram']} | {s['vanilla_ram']} | {s['front']} | {s['diff_bytes']} | {s['unverifiable']} | {s['functions_changed']} |\n")
        for s, entries, front in results:
            f.write(f"\n# overlay {s['overlay']}\n")
            if front:
                f.write(f"\n## new code at {front['ram']} ({front['size']} bytes, disassembled as thumb)\n\n```\n")
                for a, hx, ins in front['thumb']:
                    f.write(f'{a:08X} {hx:>9}  {ins}\n')
                f.write('```\n')
            for e in entries:
                if e['kind'] == 'function':
                    t = f"{e['addr']} {e['name'] or e['placeholder']}"
                    f.write(f"\n## {t}\n\n{e['mode']}, {e['size']} bytes, {e['bytes']} changed\n\n")
                    if e['changes']:
                        f.write('```\n' + ''.join(f"{c['addr']}  {c['vanilla']:<40} -> {c['redux']}\n" for c in e['changes']) + '```\n')
                else:
                    f.write(f"\n## data {e['runs'][0][0]} ({e['bytes']} bytes, {len(e['runs'])} runs)\n\n```\n")
                    for h in e['hex'][:40]:
                        f.write(f"{h['addr']}  {h['vanilla'][:64]}\n          {h['redux'][:64]}\n")
                    f.write('```\n')


def main():
    rom = R.ReduxRom()
    names = R.names()
    results = [analyse(int(a), rom, names) for a in sys.argv[1:]]
    notes = os.path.join(R.ROOT, 'notes')
    json.dump([{'stats': s, 'changes': e, 'front': fr} for s, e, fr in results],
              open(os.path.join(notes, 'overlay-changes.json'), 'w'), indent=1)
    write_md(os.path.join(notes, 'overlay-changes.md'), results)
    for s, _, _ in results:
        print(json.dumps(s))


if __name__ == '__main__':
    main()
