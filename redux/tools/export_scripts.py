#!/usr/bin/env python3
"""Decompile all event scripts (a/0/5/6) of both ROMs and summarize Redux's script changes.

  build/src/{redux,vanilla}/scripts/NNNN.s   (lossless; re-assembles byte-exact, checked here)
  notes/script-changes.md                    changed/new scripts with coverage and a sample diff
"""
import difflib, os
import ndsfs, gen5script as S
import redux_rom as R

PATH = 'a/0/5/6'


def export(rom_path, label):
    rom = ndsfs.Rom(rom_path)
    ids = {p: i for i, p in rom.paths.items()}
    files = ndsfs.narc(rom.file(ids[PATH]))
    d = os.path.join(R.BUILD, 'src', label, 'scripts')
    os.makedirs(d, exist_ok=True)
    out = []
    for i, data in enumerate(files):
        txt, st = S.decompile_best(data, R.BUILD)
        assert S.assemble_any(txt, R.BUILD) == data, (label, i)
        with open(os.path.join(d, f'{i:04d}.s'), 'w') as f:
            f.write(txt)
        out.append((txt, st))
    return out


def main():
    van = export(os.path.join(R.BUILD, 'vanilla_rom', 'black2.nds'), 'vanilla')
    red = export(os.path.join(R.BUILD, 'vanilla_rom', 'redux.nds'), 'redux')
    changed = [i for i in range(len(red)) if i >= len(van) or van[i][0] != red[i][0]]
    rows, sample = [], None
    for i in changed:
        st = red[i][1]
        cov = 100 * (st['code'] + st['move']) / max(1, st['size'])
        if i < len(van):
            d = list(difflib.unified_diff(van[i][0].split('\n'), red[i][0].split('\n'), lineterm='', n=1))
            added = sum(1 for l in d if l.startswith('+') and not l.startswith('+++'))
            removed = sum(1 for l in d if l.startswith('-') and not l.startswith('---'))
            kind = 'changed'
            if sample is None and 20 < added < 80 and cov > 90:
                sample = (i, d)
        else:
            added, removed, kind = len(red[i][0].split('\n')), 0, 'new'
        rows.append(f"| {i:04d} | {kind} | {van[i][1]['size'] if i < len(van) else 0} | {st['size']} | {st['entries']} | "
                    f"{cov:.0f}% | +{added} / -{removed} | {st['overlay'] if st['overlay'] is not None else ''} |\n")
    tot = sum(r[1]['size'] for r in red)
    dec = sum(r[1]['code'] + r[1]['move'] for r in red)
    with open(os.path.join(R.ROOT, 'notes', 'script-changes.md'), 'w') as f:
        f.write('# Redux event script changes (generated by tools/export_scripts.py)\n\n'
                f'All {len(van)} vanilla and {len(red)} Redux scripts decompile to build/src/*/scripts/ and '
                're-assemble byte-exact. Command set: PokeScriptSDK5 B2W2 definitions (base + the '
                f'best-matching overlay set per file). Overall {100 * dec / tot:.1f}% of Redux script bytes decode '
                'as instructions/movement; the rest is kept as raw .hword/.byte (padding, data, and code using '
                'undocumented overlay commands).\n\n'
                f'{len(changed)} scripts changed or added.\n\n'
                '| script | kind | vanilla B | redux B | entries | decoded | listing lines | overlay set |\n'
                '|---|---|---|---|---|---|---|---|\n')
        f.writelines(rows)
        if sample:
            f.write(f'\n## Sample: script {sample[0]:04d} (vanilla → Redux)\n\n```diff\n')
            f.write('\n'.join(sample[1][:120]) + '\n```\n')
    print(f'{len(changed)} changed; decoded {100 * dec / tot:.1f}%')


if __name__ == '__main__':
    main()
